const phoneText = (s, lang) =>
  (lang === "ckb" ? s.replace(/\d/g, (d) => "٠١٢٣٤٥٦٧٨٩"[d]) : s).replace(/ /g, "\u00a0");

const linkText = (href) => {
  const u = new URL(href);
  const host = u.host.startsWith("www.") ? u.host.slice(4) : u.host;
  const path = u.pathname.endsWith("/") ? u.pathname.slice(0, -1) : u.pathname;
  return host + path;
};

const el = (tag, cls, text) => {
  const node = document.createElement(tag);
  if (cls) node.className = cls;
  if (text != null) node.textContent = text;
  return node;
};

function render(lang) {
  const t = TEXT[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ckb" ? "rtl" : "ltr";
  document.title = t["doc.title"];
  const langBtn = document.getElementById("langBtn");
  langBtn.textContent = lang === "ckb" ? "English" : "کوردی";
  langBtn.lang = lang === "ckb" ? "en" : "ckb";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t[node.dataset.i18n];
  });

  const avatar = document.getElementById("avatar");
  if (PHOTO) {
    const img = el("img");
    img.src = PHOTO;
    img.alt = t.name;
    avatar.replaceChildren(img);
  } else {
    avatar.textContent = "MK";
    avatar.setAttribute("aria-hidden", "true");
  }

  const figures = document.getElementById("figures");
  figures.replaceChildren(...t.figures.map(([n, label]) => {
    const li = el("li");
    li.append(el("strong", null, n), el("span", null, label));
    return li;
  }));

  const grid = document.getElementById("projectGrid");
  grid.replaceChildren(...PROJECTS.map((p) => {
    const card = el("article", "card");
    card.append(el("h3", null, p.title[lang]));
    if (p.status) card.append(el("span", p.status === "development" ? "status wip" : "status", t[p.status]));
    card.append(el("p", null, p.body[lang]));
    if (p.team) card.append(el("p", "team", p.team[lang]));
    if (p.links) {
      const links = el("div", "links");
      links.append(...p.links.map((l) => {
        const href = typeof l === "string" ? l : l.href;
        const a = el("a", "link", typeof l === "string" ? linkText(l) : l.label);
        a.href = href;
        a.target = "_blank";
        a.rel = "noopener";
        return a;
      }));
      card.append(links);
    }
    const tags = el("div", "tags");
    tags.append(...p.tags.map((tag) => el("span", "tag", tag)));
    card.append(tags);
    return card;
  }));

  const skills = document.getElementById("skillGroups");
  skills.replaceChildren(...SKILLS.map((s) => {
    const box = el("div", "skill-group");
    const itemsText = typeof s.items === "string" ? s.items : s.items[lang];
    const items = el("p", null, itemsText);
    items.dir = typeof s.items === "string" || lang !== "ckb" ? "ltr" : "rtl";
    box.append(el("h3", null, s.title[lang]), items);
    return box;
  }));

  const contacts = document.getElementById("contactGrid");
  contacts.replaceChildren(...CONTACTS.map((c) => {
    const card = el("a", "contact-card");
    card.href = c.href;
    if (c.href.startsWith("https:")) {
      card.target = "_blank";
      card.rel = "noopener";
    }
    const icon = el("span", "contact-icon");
    icon.innerHTML = `<svg viewBox="0 0 24 24" width="20" height="20" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${ICONS[c.icon]}</svg>`;
    const value = el("span", "contact-value", c.phone ? phoneText(c.value, lang) : c.value);
    value.dir = "ltr";
    const text = el("span", "contact-text");
    text.append(el("span", "contact-label", typeof c.label === "string" ? c.label : c.label[lang]), value);
    card.append(icon, text);
    return card;
  }));
}

let current = "en";
try { current = localStorage.getItem("lang") || "en"; } catch (e) {}
if (!TEXT[current]) current = "en";
render(current);

document.getElementById("langBtn").addEventListener("click", () => {
  current = current === "ckb" ? "en" : "ckb";
  try { localStorage.setItem("lang", current); } catch (e) {}
  render(current);
});
